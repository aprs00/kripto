"""Regenerate the one-line-per-hypothesis index at the top of research/findings.md from its `### ` headers.

Why (2026-11-26): findings.md is ~75 KB and every session is told to read it; the headers already carry the verdict, so an index lets a
session read 80 lines and grep the details it needs. Run after editing findings (research sessions do, in step 6):

    .venv/bin/python -m scripts.findings_index          # rewrite the block between the INDEX markers
"""
from __future__ import annotations

import re
from pathlib import Path

F = Path(__file__).resolve().parents[1] / "research" / "findings.md"
A, B = "<!-- INDEX (generated by scripts.findings_index; do not edit by hand) -->", "<!-- /INDEX -->"


def build(text: str, width: int = 170) -> str:
    heads = [l[4:].strip() for l in text.splitlines() if l.startswith("### ")]
    rows = [h if len(h) <= width else h[: width - 1] + "…" for h in heads]
    return A + "\n## Index (" + str(len(rows)) + " hypotheses; details below, grep the name)\n" + "\n".join(f"- {r}" for r in rows) + "\n" + B


def apply(text: str) -> str:
    block = build(text)
    if A in text and B in text:
        return re.sub(re.escape(A) + r".*?" + re.escape(B), lambda m: block, text, flags=re.S)
    i = text.index("## Cross-cutting lessons")
    return text[:i] + block + "\n\n" + text[i:]


if __name__ == "__main__":
    F.write_text(apply(F.read_text()))
    print(f"index: {F.read_text().count(chr(10) + '- ', 0, F.read_text().index(B))} lines")
